
(function SafeFrameAI() {

    app.beginUndoGroup("SafeFrame AI Reframe");

    try {

        // Select Python-generated JSON
        var jsonFile = File.openDialog(
            "Select SafeFrame AI reframe.json",
            "*.json"
        );

        if (!jsonFile) {
            throw new Error("No JSON file selected.");
        }

        // Select original video
        var videoFile = File.openDialog(
            "Select original video",
            "*.mp4;*.mov;*.avi"
        );

        if (!videoFile) {
            throw new Error("No video selected.");
        }

        // Read JSON generated by SafeFrame AI
        jsonFile.encoding = "UTF-8";

        if (!jsonFile.open("r")) {
            throw new Error("Cannot read JSON file.");
        }

        var jsonText = jsonFile.read();
        jsonFile.close();

        // Only read trusted JSON generated by this project.
        var data;

        if (typeof JSON !== "undefined" && JSON.parse) {
            data = JSON.parse(jsonText);
        } else {
            data = eval("(" + jsonText + ")");
        }

        // Validate input structure
        if (
            !data.source ||
            !data.output ||
            !data.keyframes ||
            data.keyframes.length === 0
        ) {
            throw new Error("Invalid SafeFrame JSON.");
        }

        var sourceWidth = data.source.width;
        var sourceHeight = data.source.height;

        var compWidth = data.output.width;
        var compHeight = data.output.height;

        var fps = data.source.fps;

        if (
            sourceWidth <= 0 ||
            sourceHeight <= 0 ||
            compWidth <= 0 ||
            compHeight <= 0 ||
            fps <= 0
        ) {
            throw new Error("Invalid video dimensions or FPS.");
        }

        // Create or access AE project
        if (!app.project) {
            app.newProject();
        }

        // Import source footage
        var importOptions = new ImportOptions(videoFile);

        var footage = app.project.importFile(
            importOptions
        );

        if (!footage) {
            throw new Error("Video import failed.");
        }

        // Check footage dimensions
        if (
            footage.width !== sourceWidth ||
            footage.height !== sourceHeight
        ) {
            throw new Error(
                "Source video dimensions do not match JSON."
            );
        }

        // Create output composition
        var duration = footage.duration;

        var comp = app.project.items.addComp(
            "SafeFrame_AI_" + data.output.format,
            compWidth,
            compHeight,
            1,
            duration,
            fps
        );

        // Add video layer
        var layer = comp.layers.add(footage);

        layer.name = "SafeFrame AI - Tracked Footage";

        layer.startTime = 0;

        // Determine crop scale
        var firstCrop = data.keyframes[0].crop;

        var scaleFactor = compWidth / firstCrop.width;

        var scalePercent = scaleFactor * 100;

        // Apply constant scale
        layer.scale.setValue([
            scalePercent,
            scalePercent
        ]);

        var applied = 0;

        // Apply position keyframes
        for (var i = 0; i < data.keyframes.length; i++) {

            var item = data.keyframes[i];

            var crop = item.crop;

            var time = item.time;

            if (
                !isFinite(time) ||
                time < 0 ||
                time >= duration ||
                crop.width <= 0 ||
                crop.height <= 0
            ) {
                continue;
            }

            // Convert crop center into AE layer position.
            var cropCenterX = crop.x + crop.width / 2;
            var cropCenterY = crop.y + crop.height / 2;

            var positionX =
                compWidth / 2 -
                (cropCenterX - sourceWidth / 2) * scaleFactor;

            var positionY =
                compHeight / 2 -
                (cropCenterY - sourceHeight / 2) * scaleFactor;

            layer.position.setValueAtTime(
                time,
                [positionX, positionY]
            );

            applied++;
        }

        if (applied === 0) {
            throw new Error("No valid keyframes were applied.");
        }

        // Select composition
        comp.openInViewer();

        alert(
            "SAFEFRAME AI SUCCESS!\n\n" +
            "Composition: " + compWidth + " x " + compHeight +
            "\nFormat: " + data.output.format +
            "\nKeyframes: " + applied +
            "\n\nYour editable composition is ready."
        );

    } catch (error) {

        alert(
            "SAFEFRAME AI ERROR:\n\n" +
            error.toString()
        );

    } finally {

        app.endUndoGroup();

    }

})();
